def saved_result(root, candidate, status):
    record, metadata, receipt = candidate
    audit = {**receipt, 'artifact_approved': False, 'execution_allowed': False,
        'deployment_allowed': False, 'audit_relative_path': f"staged-artifacts/{receipt['content_sha256']}/{PATH}"}
    # Exercise the compiled writer's simplified projection, not the retained
    # authored-metadata fast path in assemble().
    value = metadata.candidate_projection()
    _, bodies = _validate(value, record, metadata.evidence, candidate=True)
    committed = bodies if status != 'blocked' else {}
    manifest = dict(run_id=RUN, package_hash=record['package_hash'], design_id=record['id'],
        design_version=record['version'], input_version=record['input_version'],
        status=status, tasks=[task.model_dump() for task in value.tasks],
        artifact_hashes={path: sha256(content.encode()).hexdigest() for path, content in committed.items()},
        staged_drafts=[audit], candidate_availability=metadata.candidate_availability(status, {PATH: audit}))
    directory = root / 'generated-drafts' / record['package_hash'] / record['id'] / str(record['version']) / RUN
    for path, content in {audit['audit_relative_path']: bodies[PATH], **committed}.items():
        target = directory / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content.encode())
    raw = json.dumps(manifest).encode()
    (directory / 'manifest.json').write_bytes(raw)
    job = dict(kind='spark_draft', status='completed', package_hash=record['package_hash'],
        design_id=record['id'], design_version=record['version'], input_version=record['input_version'],
        output={'run_id': RUN}, manifest_sha256=sha256(raw).hexdigest())
    return read_result(root, job, 'f' * 32)


@pytest.mark.parametrize('status', ['generation_complete', 'drafts_saved', 'blocked'])
def test_exact_producer_receipts_survive_saved_reader_inventory(candidate, tmp_path, status):
    record, metadata, receipt = candidate
    result = saved_result(tmp_path, candidate, status)
    before = deepcopy(result)
    manifest = result['manifest']
    availability = manifest['candidate_availability']
    assert availability['generation_complete'] is (status == 'generation_complete')
    assert availability['generation_status'] == status
    assert availability['semantic_parity'] == 'unverified'
    assert availability['execution_allowed'] is availability['deployment_allowed'] is False
    assert manifest['tasks'][0]['status'] == 'drafted'
    assert metadata.tasks['shared']['value']['status'] == 'blocked'
    assert metadata.recovery['review_issues']
    if status == 'generation_complete':
        assert result['staged_artifacts'] == {}
    else:
        assert PATH in result['staged_artifacts']
    assert (PATH in result['artifacts']) is (status != 'blocked')
    owned, files, hashes = _owned_notebooks(record['design'], manifest, result)
    assert owned == {'shared': PATH}
    assert files[PATH] == metadata.staged.files[PATH]['content']
    assert hashes[PATH] == receipt['content_sha256']
    assert hashes[PATH] == 'fd995ddd042ff4f3df5a06f3c67a9c048ed3ec4e2482acdb162ef71e84cef62b'
    assert hashes[PATH] != sha256(HELPERS['notebook']().encode()).hexdigest()
    binding = metadata.bindings[PATH]
    assert binding['receipt_sha256'] == _digest([RUN, metadata.envelope, PATH, binding['value']])
    assert binding['receipt_sha256'] != hashes[PATH]  # Metadata receipt is not a content checksum.
    assert result == before


def test_historical_blocked_schema_preserves_original_byte_checksum(candidate, tmp_path):
    record, _, _ = candidate
    result = saved_result(tmp_path, candidate, 'blocked')
    manifest = result['manifest']
    manifest['tasks'][0].update(status='blocked', artifact_paths=[], blockers=['Old writer metadata incomplete'])
    availability = manifest['candidate_availability']
    availability.pop('generation_status')
    availability.pop('generation_complete')
    # Historical JSON spacing/Unicode are hashed as saved, never reserialized.
    book = json.loads(result['staged_artifacts'][PATH])
    book['cells'][0]['source'] += ' caf\u00e9'
    content = json.dumps(book, ensure_ascii=False, indent=2) + '\n'
    digest = sha256(content.encode()).hexdigest()
    item = availability['tasks'][0]['notebooks'][0]
    item.update(content_sha256=digest, audit_relative_path=f'staged-artifacts/{digest}/{PATH}')
    result['staged_artifacts'][PATH] = content
    before = deepcopy(result)
    owned, files, hashes = _owned_notebooks(record['design'], manifest, result)
    assert owned == {'shared': PATH} and files[PATH] == content and hashes[PATH] == digest
    assert result == before


@pytest.mark.parametrize('status', ['generation_complete', 'drafts_saved', 'blocked'])
@pytest.mark.parametrize('tamper', ['hash', 'raw_hash', 'metadata_hash', 'bytes', 'audit_path',
    'path', 'owner', 'committed_owner', 'ownership_basis', 'missing', 'staged_conflict'])
def test_forged_receipts_remain_fail_closed(candidate, tmp_path, status, tamper):
    record, metadata, _ = candidate
    result = saved_result(tmp_path, candidate, status)
    manifest = result['manifest']
    availability = manifest['candidate_availability']
    item = availability['tasks'][0]['notebooks'][0]
    if tamper == 'hash':
        item['content_sha256'] = 'f' * 64
    elif tamper == 'raw_hash':
        item['content_sha256'] = sha256(HELPERS['notebook']().encode()).hexdigest()
    elif tamper == 'metadata_hash':
        item['content_sha256'] = metadata.bindings[PATH]['receipt_sha256']
    elif tamper == 'bytes':
        for inventory in (result['artifacts'], result['staged_artifacts']):
            if PATH in inventory:
                inventory[PATH] += ' '
    elif tamper == 'audit_path':
        item['audit_relative_path'] = f"staged-artifacts/{'f' * 64}/{PATH}"
    elif tamper == 'path':
        item['relative_path'] = 'notebooks/../escape.ipynb'
    elif tamper == 'owner':
        availability['tasks'][0]['task_id'] = 'outside'
    elif tamper == 'committed_owner':
        # Even a known task cannot adopt another task's committed notebook.
        record['design']['tasks'].append(dict(id='other', implementation_kind='notebook_task'))
        manifest['tasks'].append(dict(task_id='other', artifact_paths=[]))
        availability['tasks'].append({**deepcopy(availability['tasks'][0]), 'task_id': 'other'})
        result['artifacts'][PATH] = metadata.staged.files[PATH]['content']
        result['staged_artifacts'].clear()
    elif tamper == 'ownership_basis':
        availability['task_ownership_basis'] = 'guessed'
    elif tamper == 'missing':
        result['artifacts'].clear()
        result['staged_artifacts'].clear()
    else:
        # Correct committed bytes must never mask a present corrupt staged body.
        result['artifacts'][PATH] = metadata.staged.files[PATH]['content']
        result['staged_artifacts'][PATH] = 'corrupt staged bytes'
    if tamper in {'hash', 'raw_hash', 'metadata_hash'}:
        # An internally consistent audit path must not bypass content equality.
        item['audit_relative_path'] = f"staged-artifacts/{item['content_sha256']}/{PATH}"
    with pytest.raises(HTTPException) as error:
        _owned_notebooks(record['design'], manifest, result)
    assert error.value.status_code == 409